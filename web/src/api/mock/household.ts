function fakeSha(seed: string): string {
  // deterministic 64-hex string, visibly fake-but-shaped
  let h = 0x811c9dc5;
  let out = '';
  for (let i = 0; i < 64; i++) {
    h ^= seed.charCodeAt(i % seed.length) + i;
    h = Math.imul(h, 0x01000193) >>> 0;
    out += (h & 0xf).toString(16);
  }
  return out;
}

